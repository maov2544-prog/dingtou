package com.aolandai.dingtou.service.qianchuan;

/**
 * 账户路由模式：查千川计划时，先扫哪几个投放账户。
 *
 * <p><b>为什么需要它：</b>{@code planQuery} 原来是无脑遍历全部 8 个投放账户。
 * 修完「乘方场景」后每个账户要查 {@code UNI_PROJECT} + {@code OVERALL_PROJECT} 两个场景，
 * 单次查询从 8 次调用涨到 16 次 → 触发 40100 频控 → 耗时从 7 秒涨到 68 秒。
 * 用《定向投放登记表》把【抖音号 + 商品名】先定位到账户，就只查那一个账户。</p>
 *
 * <p>⚠️ <b>但登记表覆盖率极低</b>（抖音号 5 个 vs 素材表 1988 个），所以默认 {@link #AUTO}
 * 必须「未命中就回退全量」—— 否则未命中会被当成「没有计划」→ 重复建计划（花钱）。</p>
 */
public enum AccountRoutingMode {

    /**
     * <b>定位优先，未命中回退全量（默认，最安全）。</b>
     *
     * <p>命中 → 只查定位到的账户；未命中 / 登记表读不动 / 账户名换不成账户 ID →
     * 回退全量扫描，并记一条 warning 说明「为什么回退」。</p>
     */
    AUTO("定位优先，未命中回退全量"),

    /**
     * <b>只用登记表定位，未命中就不查（有漏判风险，仅供登记表填全之后使用）。</b>
     *
     * <p>⚠️⚠️ <b>这个模式会漏判</b>：登记表没填全时，未命中意味着「一个账户都不查」
     * → 对外表现为「该组合没有千川计划」→ 重复建计划（<b>花钱</b>）。
     * 只在登记表已经覆盖全部在投组合、且你想用「查不到即报错」来倒逼补表时才开。</p>
     */
    TABLE_ONLY("只用登记表定位，未命中不查"),

    /**
     * <b>永远全量扫描（老行为，排障对比用）。</b>
     *
     * <p>不看登记表，8 个账户全查。用于对比「定位结果」与「全量结果」是否一致，
     * 以及登记表出问题时的临时降级。</p>
     */
    SCAN_ALL("永远全量扫描");

    private final String label;

    AccountRoutingMode(String label) {
        this.label = label;
    }

    public String label() {
        return label;
    }
}
